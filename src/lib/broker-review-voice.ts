export function reviewSectionOutline(ymd: string, mode: DayMode = "work"): string {
  if (mode === "rest") {
    return `## ${ymd} · 收工时刻
### 今日切片
### 生活手记
### 生活隙
### 团留言
### 经纪人说`;
  }
  return `## ${ymd} · 收工片刻
### 今日切片
### 工作台手记
### 生活隙
### 仍悬而未决
### 团留言
### 经纪人说`;
}

export function buildBrokerReviewUserPrompt(
  ymd: string,
  recordBlocks: string,
  todoLines: string,
  teamTriggerHints = "",
  mode: DayMode = "work",
): string {
  if (mode === "rest") {
    return buildBrokerRestReviewUserPrompt(ymd, recordBlocks, teamTriggerHints);
  }

  const teamBlock = teamTriggerHints.trim()
    ? `\n${teamTriggerHints.trim()}\n`
    : "";

  return `请为 ${ymd} 写一份日终复盘（Markdown，不要 JSON）。

【内容底线】
1) 只根据下方材料写，具体项目/事项必须出现，禁止用「商务推进、内容输出、数据分析」等标签糊弄；
2) 材料里「待补充」的章节，用温柔口吻点出缺口（缺明日计划、缺风险记录等），并给一句可操作的补记建议；
3) 「未完成待办」合并日报 □ 待确认与系统待办，去重；会议名勿拆开（如「金币互动周会」）。

【表达形态】
- 标题与章节名必须严格使用下方「输出结构」，不要改成其它小节名；
- 「今日切片」：按项目或时段叙述，可用 1～2 段散文 + 少量条目，避免机械罗列「｜」分隔符堆叠；材料含上午/下午等时段时须覆盖，勿从午后凭空起笔；
- 「工作台手记」：用三个加粗小标题组织（不要用「亮点/卡点/明天建议」字样）：
  - **闪过的光**（今日真正推进了什么，≥2 点）
  - **未散的雾**（阻塞、空白、待确认，≥2 点）
  - **明日的一盏灯**（明天先做什么，≥2 点，具体可执行）
- 「生活隙」：有生活记录则写一段有余温的短文字；没有则一句轻柔提醒，勿编造事件；
- 「仍悬而未决」：列表或短句，列出待确认/待办；
- 「团留言」：0～2 条，每条格式 \`- **角色名**：1～2 句（观察 + 明日一个可执行小动作）\`；角色只能从职业教练、复原顾问、育儿同伴中选；参照下方「用时摘录」「睡眠摘录」与顾问触发，「不出镜」的顾问不要写；若材料含多项用时，职业教练必须点到具体时长；若含睡眠数据，复原顾问必须点到入睡/起床或时长；复原顾问与育儿同伴同日最多出现其一；若三位都不出镜，写一行「今日顾问未出镜，首席已收束。」；
- 「经纪人说」：2～4 句，像懂你的朋友在收工时说的话，收束全文（勿重复团留言原话）。

今日记录（已按章节解析）:
${recordBlocks || "（今日无记录）"}
${teamBlock}
系统未完成待办:
${todoLines || "（无）"}

输出结构（二级/三级标题按顺序，不要省略、不要改名）:
${reviewSectionOutline(ymd, "work")}`;
}

export function buildBrokerRestReviewUserPrompt(
  ymd: string,
  recordBlocks: string,
  teamTriggerHints = "",
): string {
  const teamBlock = teamTriggerHints.trim()
    ? `\n${teamTriggerHints.trim()}\n`
    : "";

  return `请为 ${ymd} 写一份**休息日**收工复盘（Markdown，不要 JSON）。

【休息日底线 — 必须遵守】
1) 这是休息日：全文不得出现工作项目、会议、系统待办、职业教练，不得建议「明天先处理 XX 工作」；
2) 只根据下方「今日生活记录」写，禁止引用未出现的项目名（AE农场、社媒、趋势洞察、周会等一律不许写）；
3) 不要写「工作日志空白」「待确认事项待补」等工作语境；若生活记录已够，不必提醒补工作日报；
4) 不要输出「仍悬而未决」章节（工作待办与用户今日无关）。

【表达形态】
- 标题与章节名必须严格使用下方「输出结构」；
- 「今日切片」：按时段或主题写 1～2 段散文，呈现这一天如何被生活填满；
- 「生活手记」：用三个加粗小标题组织（不要用「工作台」「亮点/卡点/明天建议」字样）：
  - **闪过的光**（今日值得记住的生活瞬间，≥2 点）
  - **未散的雾**（疲惫、分心、情绪或未竟的生活小事，≥1 点；勿写工作相关）
  - **留给明天**（明天的生活向小意图，如睡眠、运动、陪伴，≥1 点；禁止工作事项）
- 「生活隙」：有余温的短文字，点出感官或情绪细节；
- 「团留言」：0～4 条，每条格式 \`- **角色名**：1～2 句\`；角色从生活教练、健身教练、休息教练中选（有信号者出镜）；**若下方顾问触发标明育儿同伴必须出镜，则团留言中必须包含育儿同伴一条**；参照下方摘录，「不出镜」的顾问不要写；若都不出镜，写「今日顾问未出镜，首席已收束。」；
- 「经纪人说」：2～3 句，鼓励收工、肯定休息的价值，不提工作。

今日生活记录:
${recordBlocks || "（今日无记录）"}
${teamBlock}

输出结构（二级/三级标题按顺序，不要省略、不要改名）:
${reviewSectionOutline(ymd, "rest")}`;
}

/** 从复盘 Markdown 主标题提取日历日；无法识别时返回 null */
export function extractReviewMarkdownDate(md: string): string | null {
  const m = md.match(/^##\s+(\d{4}-\d{2}-\d{2})\s*[·\-—.]/m);
  return m?.[1] ?? null;
}

/** 复盘标题日期须与请求的日历日一致 */
export function reviewMarkdownMatchesDate(md: string, ymd: string): boolean {
  const head = extractReviewMarkdownDate(md);
  if (!head) return true;
  return head === ymd;
}

